let marks = 577;

if (marks > 75 && marks <= 100) {
    console.log("A Grade");
} else if (marks > 60 && marks <= 75) {
    console.log("B Grade");
} else if (marks > 45 && marks <= 60) {
    console.log("C Grade");
} else if (marks >= 0 && marks <= 45) {
    console.log("D Grade");
} else {
    console.log("Not Possible");
}
